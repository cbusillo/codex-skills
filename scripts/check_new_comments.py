#!/usr/bin/env python3
# /// script
# requires-python = ">=3.12"
# dependencies = []
# ///
from __future__ import annotations

import argparse
import ast
import codecs
import io
import itertools
import re
import subprocess
import sys
import tokenize
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

GUIDE = "https://github.com/cbusillo/codex-skills/blob/main/skills/references/python-odoo-style.md#names-instead-of-comments"
HUNK = re.compile(r"^@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@")
DIRECTIVE = re.compile(
    r"(?:ruff: )?noqa: ?[A-Z]+\d+(?:, ?[A-Z]+\d+)*"
    r"|(?:type|pyright): ignore\[[\w-]+(?:, ?[\w-]+)*]"
    r"|noinspection \w+(?:,\w+)*"
    r"|fmt: (?:off|on|skip)"
    r"|pragma: no cover"
)
LINK = re.compile(r"#\s*<?https?://\S+>?")
LICENSE_MARKER = re.compile(r"spdx-license-identifier:|copyright|license file|^#\s*licen[cs]ed?\b", re.IGNORECASE)
GENERATED_MARKER = re.compile(r"@generated|generated by|do not edit", re.IGNORECASE)
SCRIPT_METADATA = re.compile(r"(?m)^# /// script\n(?:#(?:| .*)\n)+# ///$")
MESSAGES = {
    "comment": f"New comment: carry the reason in a name, a test, or a link-only comment; see {GUIDE}",
    "unparsed": "Python could not parse this file, so its new comments are unchecked; fix the syntax.",
}


@dataclass(frozen=True, order=True)
class Finding:
    path: str
    line: int
    kind: str


@dataclass
class FileDiff:
    old_path: str | None
    new_path: str | None
    removed: set[int] = field(default_factory=set)
    added: set[int] = field(default_factory=set)


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


def diff_path(raw: str, prefix: str) -> str | None:
    if raw == "/dev/null":
        return None
    if raw.startswith('"'):
        raw = codecs.escape_decode(raw[1:-1].encode())[0].decode()
    return raw.removeprefix(prefix)


def parse_diff(diff: str) -> list[FileDiff]:
    files: list[FileDiff] = []
    in_header = False
    old_line = new_line = 0
    for line in diff.splitlines():
        if line.startswith("diff --git "):
            in_header = True
            files.append(FileDiff(None, None))
        elif in_header and line.startswith("--- "):
            files[-1].old_path = diff_path(line[4:], "a/")
        elif in_header and line.startswith("+++ "):
            files[-1].new_path = diff_path(line[4:], "b/")
        elif hunk := HUNK.match(line):
            in_header, old_line, new_line = False, int(hunk.group(1)), int(hunk.group(2))
        elif in_header:
            continue
        elif line.startswith("+"):
            files[-1].added.add(new_line)
            new_line += 1
        elif line.startswith("-"):
            files[-1].removed.add(old_line)
            old_line += 1
    return files


def is_directive(comment: str) -> bool:
    parts = [part.strip() for part in comment.split("#")[1:]]
    return all(DIRECTIVE.fullmatch(part) for part in parts)


def metadata_rows(source: str) -> set[int]:
    rows: set[int] = set()
    for block in SCRIPT_METADATA.finditer(source):
        first = source.count("\n", 0, block.start()) + 1
        rows.update(range(first, first + block.group().count("\n") + 1))
    return rows


def leading_comments(lines: list[str]) -> list[str]:
    return list(itertools.takewhile(lambda line: line.startswith("#"), lines))


def header_rows(lines: list[str]) -> set[int]:
    return {
        number
        for number, line in enumerate(leading_comments(lines), start=1)
        if (number == 1 and line.startswith("#!")) or LICENSE_MARKER.search(line)
    }


def is_generated(lines: list[str]) -> bool:
    return any(GENERATED_MARKER.search(line) for line in leading_comments(lines))


def comments(source: str) -> tuple[list[tokenize.TokenInfo], bool]:
    found = []
    try:
        for token in tokenize.generate_tokens(io.StringIO(source).readline):
            if token.type == tokenize.COMMENT:
                found.append(token)
    except (SyntaxError, tokenize.TokenError):
        return found, False
    return found, True


def take_moved(removed: Counter[str], text: str) -> bool:
    if removed[text] == 0:
        return False
    removed[text] -= 1
    return True


def file_findings(path: str, source: str, added: set[int], old: Counter[str]) -> list[Finding]:
    lines = source.splitlines()
    if is_generated(lines):
        return []
    allowed = metadata_rows(source) | header_rows(lines)
    tokens, tokenized = comments(source)
    findings = [
        Finding(path, token.start[0], "comment")
        for token in tokens
        if token.start[0] in added
        and token.start[0] not in allowed
        and not is_directive(token.string)
        and not LINK.fullmatch(token.string.strip())
        and not take_moved(old, token.string.strip())
    ]
    try:
        ast.parse(source)
    except SyntaxError:
        tokenized = False
    if not tokenized:
        findings.append(Finding(path, 1, "unparsed"))
    return findings


def scan(repo: Path, base: str) -> list[Finding]:
    base = git(repo, "merge-base", base, "HEAD").strip()
    files = parse_diff(git(repo, "diff", "--find-renames", "--unified=0", "--no-color", base, "HEAD", "--", "*.py"))
    old: Counter[str] = Counter()
    for change in files:
        if change.old_path and change.removed:
            source = git(repo, "show", f"{base}:{change.old_path}")
            old.update(token.string.strip() for token in comments(source)[0] if token.start[0] in change.removed)
    findings: list[Finding] = []
    for change in files:
        if change.new_path and change.added:
            findings += file_findings(change.new_path, git(repo, "show", f"HEAD:{change.new_path}"), change.added, old)
    return sorted(set(findings))


def report(findings: list[Finding], output_format: str) -> None:
    for finding in findings:
        if output_format == "github":
            print(f"::error file={finding.path},line={finding.line},title=python-odoo-style::{MESSAGES[finding.kind]}")
        else:
            print(f"{finding.path}:{finding.line}: {MESSAGES[finding.kind]}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Fail on comments that a diff adds to Python files.")
    parser.add_argument("--repo", type=Path, default=Path())
    parser.add_argument(
        "--base", required=True, help="Branch or commit to compare with; the diff starts at its merge base with HEAD"
    )
    parser.add_argument("--format", choices=("text", "github"), default="text")
    args = parser.parse_args(argv)
    try:
        findings = scan(args.repo, args.base)
    except subprocess.CalledProcessError as error:
        print(f"error: git {' '.join(error.cmd[3:])} failed: {error.stderr.strip()}", file=sys.stderr)
        return 2
    report(findings, args.format)
    return 1 if findings else 0


if __name__ == "__main__":
    raise SystemExit(main())
