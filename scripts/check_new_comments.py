#!/usr/bin/env python3
# /// script
# requires-python = ">=3.12"
# dependencies = []
# ///
from __future__ import annotations

import argparse
import ast
import io
import re
import subprocess
import sys
import tokenize
from dataclasses import dataclass
from pathlib import Path

GUIDE = "https://github.com/cbusillo/codex-skills/blob/main/skills/references/python-odoo-style.md#names-instead-of-comments"
HUNK = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")
DIRECTIVE = re.compile(
    r"(?:ruff: )?noqa: ?[A-Z]+\d+(?:, ?[A-Z]+\d+)*"
    r"|(?:type|pyright): ignore\[[\w-]+(?:, ?[\w-]+)*]"
    r"|noinspection \w+(?:,\w+)*"
    r"|fmt: (?:off|on|skip)"
    r"|pragma: no cover"
)
LINK = re.compile(r"#\s*<?https?://\S+>?")
HEADER_MARKER = re.compile(r"copyright|licen[cs]e|spdx-license-identifier|@generated|generated by|do not edit", re.IGNORECASE)
SCRIPT_METADATA = re.compile(r"(?m)^# /// [a-zA-Z0-9-]+\n(?:#(?:| .*)\n)+# ///$")


@dataclass(frozen=True, order=True)
class Finding:
    path: str
    line: int
    kind: str


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


def parse_diff(diff: str) -> tuple[dict[str, dict[int, str]], set[str]]:
    added: dict[str, dict[int, str]] = {}
    removed: set[str] = set()
    current: dict[int, str] | None = None
    in_header = False
    line_number = 0
    for line in diff.splitlines():
        if line.startswith("diff --git "):
            in_header, current = True, None
        elif in_header and line.startswith("+++ "):
            path = line[4:].removeprefix("b/")
            current = None if path == "/dev/null" else added.setdefault(path, {})
        elif hunk := HUNK.match(line):
            in_header, line_number = False, int(hunk.group(1))
        elif in_header:
            continue
        elif line.startswith("+") and current is not None:
            current[line_number] = line[1:].strip()
            line_number += 1
        elif line.startswith("-"):
            removed.add(line[1:].strip())
    return added, removed


def new_lines(added: dict[int, str], removed: set[str]) -> set[int]:
    return {number for number, text in added.items() if text not in removed}


def is_directive(comment: str) -> bool:
    parts = [part.strip() for part in comment.split("#")[1:]]
    return all(DIRECTIVE.fullmatch(part) for part in parts)


def metadata_rows(source: str) -> set[int]:
    rows: set[int] = set()
    for block in SCRIPT_METADATA.finditer(source):
        first = source.count("\n", 0, block.start()) + 1
        rows.update(range(first, first + block.group().count("\n") + 1))
    return rows


def header_rows(lines: list[str]) -> set[int]:
    header: list[int] = []
    for number, line in enumerate(lines, start=1):
        if not line.startswith("#"):
            break
        header.append(number)
    if any(HEADER_MARKER.search(lines[number - 1]) for number in header):
        return set(header)
    return {1} if lines and lines[0].startswith("#!") else set()


def comment_findings(path: str, source: str, new: set[int]) -> list[Finding]:
    allowed = metadata_rows(source) | header_rows(source.splitlines())
    findings = []
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        row = token.start[0]
        if token.type != tokenize.COMMENT or row not in new or row in allowed:
            continue
        if is_directive(token.string) or LINK.fullmatch(token.string.strip()):
            continue
        findings.append(Finding(path, row, "comment"))
    return findings


def docstring_findings(path: str, source: str, new: set[int]) -> list[Finding]:
    findings = []
    for node in ast.walk(ast.parse(source)):
        if not isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef) or not node.body:
            continue
        first = node.body[0]
        if not (isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str)):
            continue
        if new & set(range(first.lineno, (first.end_lineno or first.lineno) + 1)):
            findings.append(Finding(path, first.lineno, "docstring"))
    return findings


def scan(repo: Path, base: str) -> list[Finding]:
    diff = git(repo, "diff", "--find-renames", "--unified=0", "--no-color", base, "HEAD", "--", "*.py")
    added, removed = parse_diff(diff)
    findings: list[Finding] = []
    for path, lines in added.items():
        new = new_lines(lines, removed)
        if not new:
            continue
        source = git(repo, "show", f"HEAD:{path}")
        try:
            findings += comment_findings(path, source, new) + docstring_findings(path, source, new)
        except (SyntaxError, tokenize.TokenError):
            continue
    return sorted(set(findings))


def message(finding: Finding) -> str:
    return f"New {finding.kind}: carry the reason in a name, a test, or a link-only comment; see {GUIDE}"


def report(findings: list[Finding], output_format: str) -> None:
    for finding in findings:
        if output_format == "github":
            print(f"::error file={finding.path},line={finding.line},title=New {finding.kind}::{message(finding)}")
        else:
            print(f"{finding.path}:{finding.line}: {message(finding)}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Fail on comments and docstrings that a diff adds to Python files.")
    parser.add_argument("--repo", type=Path, default=Path())
    parser.add_argument("--base", required=True, help="Commit the diff starts from, such as HEAD^1 in CI")
    parser.add_argument("--format", choices=("text", "github"), default="text")
    args = parser.parse_args(argv)
    try:
        findings = scan(args.repo, args.base)
    except subprocess.CalledProcessError as error:
        print(f"error: git {' '.join(error.cmd[3:])} failed: {error.stderr.strip()}", file=sys.stderr)
        return 2
    report(findings, args.format)
    return 1 if findings else 0


if __name__ == "__main__":
    raise SystemExit(main())
