from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from launchplane_contract import BOUNDED_READ_RESPONSE_FIELDS, bounded_read_path  # noqa: E402

MAX_OPENAPI_BYTES = 16 * 1024 * 1024
ALLOWLIST_LOCATION = "BOUNDED_READ_RESPONSE_FIELDS in skills/launchplane/scripts/launchplane_contract.py"


def read_openapi(path: Path) -> dict[str, Any]:
    with path.open("rb") as source:
        body = source.read(MAX_OPENAPI_BYTES + 1)
    if len(body) > MAX_OPENAPI_BYTES:
        raise ValueError("OpenAPI document is too large")
    return json.loads(body)


def response_fields(openapi: dict[str, Any], path: str) -> set[str]:
    schemas = openapi["components"]["schemas"]
    schema = openapi["paths"][path]["get"]["responses"]["200"]["content"]["application/json"]["schema"]
    while "$ref" in schema:
        schema = schemas[schema["$ref"].removeprefix("#/components/schemas/")]
    properties = schema["properties"]
    if not isinstance(properties, dict) or not properties:
        raise ValueError(f"{path} declares no response fields")
    return set(properties)


def unaccepted_fields(openapi: dict[str, Any]) -> dict[str, list[str]]:
    declared = {command: response_fields(openapi, bounded_read_path(command)) for command in sorted(BOUNDED_READ_RESPONSE_FIELDS)}
    return {
        command: sorted(fields - BOUNDED_READ_RESPONSE_FIELDS[command])
        for command, fields in declared.items()
        if fields - BOUNDED_READ_RESPONSE_FIELDS[command]
    }


def run(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Check that every field a generated Launchplane OpenAPI document declares for a bounded read is in that read's allowlist."
    )
    parser.add_argument("--openapi", type=Path, required=True, help="Schema generated by launchplane service export-openapi")
    args = parser.parse_args(argv)
    try:
        unaccepted = unaccepted_fields(read_openapi(args.openapi))
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"unavailable: could not derive read fields from {args.openapi} ({type(exc).__name__}: {exc})", file=sys.stderr)
        return 2
    for command, fields in unaccepted.items():
        print(
            f"unaccepted: {command} declares {', '.join(fields)}. Add each to its read in {ALLOWLIST_LOCATION}, "
            "projecting it only when the read should emit it, and land that catalog change first.",
            file=sys.stderr,
        )
    if unaccepted:
        return 1
    print(f"accepted: every field {args.openapi} declares for {len(BOUNDED_READ_RESPONSE_FIELDS)} bounded reads is in its allowlist")
    return 0


if __name__ == "__main__":
    raise SystemExit(run(sys.argv[1:]))
