from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from launchplane_contract import BOUNDED_READ_RESPONSE_FIELDS, bounded_read_path  # noqa: E402
from launchplane_reply_schema import check_or_write_pin  # noqa: E402

PIN_PATH = Path(__file__).resolve().parent.parent / "references" / "launchplane-read-response-fields.json"
MAX_OPENAPI_BYTES = 16 * 1024 * 1024


def read_openapi(path: Path) -> dict[str, Any]:
    with path.open("rb") as source:
        body = source.read(MAX_OPENAPI_BYTES + 1)
    if len(body) > MAX_OPENAPI_BYTES:
        raise ValueError("OpenAPI document is too large")
    return json.loads(body)


def response_fields(openapi: dict[str, Any], path: str) -> list[str]:
    schemas = openapi["components"]["schemas"]
    schema = openapi["paths"][path]["get"]["responses"]["200"]["content"]["application/json"]["schema"]
    while "$ref" in schema:
        schema = schemas[schema["$ref"].removeprefix("#/components/schemas/")]
    properties = schema["properties"]
    if not isinstance(properties, dict) or not properties:
        raise ValueError(f"{path} declares no response fields")
    return sorted(properties)


def render_pin(openapi: dict[str, Any]) -> bytes:
    reads = {command: response_fields(openapi, bounded_read_path(command)) for command in sorted(BOUNDED_READ_RESPONSE_FIELDS)}
    return (json.dumps(reads, indent=2, sort_keys=True) + "\n").encode()


def run(argv: list[str], *, pin: Path = PIN_PATH) -> int:
    parser = argparse.ArgumentParser(description="Compare pinned read fields with a generated Launchplane OpenAPI document.")
    parser.add_argument("command", choices=("check", "sync"))
    parser.add_argument("--openapi", type=Path, required=True, help="Schema generated by launchplane service export-openapi")
    args = parser.parse_args(argv)
    try:
        upstream = render_pin(read_openapi(args.openapi))
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"unavailable: could not derive read fields from {args.openapi} ({type(exc).__name__}: {exc})", file=sys.stderr)
        return 2
    sync_steps = (
        "`uv run skills/launchplane/scripts/sync-read-response-fields.py sync --openapi <generated-schema>`, "
        "add each new field to its read in BOUNDED_READ_RESPONSE_FIELDS,"
    )
    return check_or_write_pin(args.command, pin, upstream, str(args.openapi), sync_steps)


if __name__ == "__main__":
    raise SystemExit(run(sys.argv[1:]))
